# Колонки листа: A Категория | B Подкатегория | C Название | D Описание | E пусто |
# F Адрес | G Район | H Координаты | I Фото | J VK | K TG | L IG | M Сайт | N Телефон | O Время | P Меню
def append_rows(ws, rows):
    # найти последнюю строку с данными
    last = 1
    for r in range(2, ws.max_row + 1):
        if any(c.value not in (None, "") for c in ws[r]):
            last = r
    start = last + 1
    for i, row in enumerate(rows):
        # row: (категория, подкатегория, название, описание, адрес, район, координаты, телефон, время)
        (cat, sub, name, desc, addr, district, coord, phone, hours) = row
        r = start + i
        ws.cell(r, 1, cat)
        if sub:
            ws.cell(r, 2, sub)
        ws.cell(r, 3, name)
        ws.cell(r, 4, desc)
        ws.cell(r, 6, addr)      # F
        ws.cell(r, 7, district)  # G
        ws.cell(r, 8, coord)     # H
        if phone:
            ws.cell(r, 14, phone)    # N
        if hours:
            ws.cell(r, 15, hours)    # O
    return start, len(rows)


