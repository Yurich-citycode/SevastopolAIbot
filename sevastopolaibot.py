async def show_nearby_food(
    call: types.CallbackQuery,
    state: FSMContext,
    place_type: str,
    category: str,
    index: int
):

    state_data = await state.get_data()

    if place_type == "loc":

        places = (
            state_data.get("loc_places")
            or [
                r for r in get_places_from_sheet("Локации")
                if category.lower() in str(
                    r.get("Категория", "")
                ).lower()
            ]
        )

    else:

        places = (
            state_data.get("rt_places")
            or [
                r for r in get_places_from_sheet("Маршруты")
                if category.lower() in str(
                    r.get("Категория", "")
                ).lower()
            ]
        )

    if not places or index >= len(places):
        await call.answer(
            "Место не найдено 😔",
            show_alert=True
        )
        return

    target_place = places[index]

    coords_str = str(
        target_place.get("Координаты", "")
    ).strip()

    if not coords_str or "," not in coords_str:
        await call.answer(
            "У этого места нет координат для поиска еды 😔",
            show_alert=True
        )
        return

    try:

        lat_str, lon_str = coords_str.split(",")

        target_lat = float(
            lat_str.strip()
        )

        target_lon = float(
            lon_str.strip()
        )

    except Exception:

        await call.answer(
            "Ошибка в координатах локации.",
            show_alert=True
        )
        return

    all_food_places = []

    for sheet_cat in cat_map.values():

        food_items = get_places_from_sheet(
            sheet_cat
        )

        if food_items:
            all_food_places.extend(
                food_items
            )

    places_with_distance = []

    for p in all_food_places:

        p_copy = p.copy()

        f_coords = str(
            p_copy.get("Координаты", "")
        ).strip()

        if f_coords and "," in f_coords:

            try:

                f_lat, f_lon = f_coords.split(",")

                dist = calculate_distance(
                    target_lat,
                    target_lon,
                    float(f_lat.strip()),
                    float(f_lon.strip())
                )

                p_copy["distance"] = dist

                places_with_distance.append(
                    p_copy
                )

            except Exception:
                continue

    if not places_with_distance:

        await call.answer(
            "Рядом ничего вкусного не найдено 😔",
            show_alert=True
        )
        return

    places_with_distance.sort(
        key=lambda x: x.get(
            "distance",
            999999
        )
    )

    nearest_food = places_with_distance[:10]

    await state.update_data(
        filtered_places=nearest_food,
        current_category="nearfood"
    )

    text, markup, photo_url = create_carousel_card(
        nearest_food,
        0,
        "nearfood"
    )

    await send_card(
        call,
        text,
        markup,
        photo_url
    )

    await call.answer()

