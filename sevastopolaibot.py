async def update_sheets_cache():
    """
    Фоновая задача: скачивает таблицу и полностью обновляет кэш в памяти.
    Работает асинхронно, карусели при этом не зависают.
    """
    url = f"https://docs.google.com/spreadsheets/d/{SPREADSHEET_ID}/export?format=xlsx"

    while True:
        try:
            print("🔄 [КЭШ] Начинаю фоновое обновление данных из Google Sheets...")

            # Читаем Excel асинхронно, чтобы чтение тяжелого файла не вешало бота
            loop = asyncio.get_event_loop()
            excel_file = await loop.run_in_executor(None, pd.ExcelFile, url)
            sheet_names = excel_file.sheet_names
            cleaned_sheets = {name.strip(): name for name in sheet_names}

            # 1. Кэшируем вкладку "Где поесть?"
            target_food = "Где поесть?" if "Где поесть?" in cleaned_sheets else sheet_names[0]
            df_food = await loop.run_in_executor(None, lambda: pd.read_excel(url, sheet_name=target_food).fillna(''))
            TABLE_CACHE["Где поесть"] = df_food.to_dict(orient='records')
            print(f"👍 [КЭШ] Вкладка 'Где поесть' успешно загружена. Строк: {len(TABLE_CACHE['Где поесть'])}")

            # 2. Кэшируем остальные важные вкладки
            for sheet_key in ["Локации", "Маршруты", "События"]:
                if sheet_key in cleaned_sheets:
                    real_name = cleaned_sheets[sheet_key]
                    df_other = await loop.run_in_executor(None, lambda: pd.read_excel(url, sheet_name=real_name).fillna(''))
                    TABLE_CACHE[sheet_key] = df_other.to_dict(orient='records')
                    print(f"👍 [КЭШ] Вкладка '{sheet_key}' успешно загружена. Строк: {len(TABLE_CACHE[sheet_key])}")
                else:
                    print(f"⚠️ [КЭШ] Вкладка '{sheet_key}' не найдена в Google-таблице.")

            print("✅ [КЭШ] Все данные успешно обновлены в памяти и готовы к моментальной выдаче!")

        except Exception as e:
            print(f"❌ [КЭШ] Ошибка при фоновом обновлении таблицы: {e}")

        # Повторяем процедуру каждые 10 минут (600 секунд)
        await asyncio.sleep(600)


