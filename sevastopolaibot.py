def get_rank(xp):
    if xp < 100: return "Гость города"
    elif xp < 300: return "Житель"
    elif xp < 800: return "Исследователь"
    elif xp < 2000: return "Проводник"
    elif xp < 4000: return "Амбассадор"
    elif xp < 7000: return "Легенда города"
    else: return "City Code"

def get_progress_bar(xp):
    levels = [0, 100, 300, 800, 2000, 4000, 7000]
    for i in range(len(levels)-1):
        if xp < levels[i+1]:
            progress = int((xp - levels[i]) / (levels[i+1] - levels[i]) * 10)
            return "▓" * progress + "░" * (10 - progress)
    return "▓" * 10

def xp_to_next(xp):
    levels = [100, 300, 800, 2000, 4000, 7000]
    for lvl in levels:
        if xp < lvl:
            return lvl - xp
    return 0

